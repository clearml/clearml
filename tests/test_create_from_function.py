"""Tests for the task template generated for function based pipeline steps.

A ``PipelineController`` function step is executed by ClearML as a standalone
task.  The task script is generated by
:class:`clearml.backend_interface.task.populate.CreateFromFunction` and it has
to pass the pipeline parameter values to the user function *with the type that
was declared for them* (``param_type`` in ``PipelineController.add_parameter``
or the type hint of the function argument).
"""

from unittest import mock

# The parameters the fake task returns, they are set by the test itself.
_TASK_PARAMETERS = {}


class _FakeTask:
    """Minimal stand-in for ``clearml.Task`` used to run the generated script."""

    def __init__(self, parameters=None):
        self.parameters = parameters if parameters is not None else {}
        self.connected = {}
        self.uploaded = []

    @staticmethod
    def init(*args, **kwargs):
        return _FakeTask(_TASK_PARAMETERS)

    def connect(self, configuration, name=None, **kwargs):
        self.connected[name] = configuration

    def get_parameters(self, cast=False):
        return dict(self.parameters)

    def upload_artifact(self, name=None, artifact_object=None, **kwargs):
        self.uploaded.append((name, artifact_object))

    def _set_parameters(self, parameters, **kwargs):
        self.parameters.update(parameters)

    @staticmethod
    def get_task(task_id=None, **kwargs):
        raise AssertionError("no parent task is expected in this test")


def _add_two(x: int):
    """Return ``x`` increased by two, used to check the type of the argument."""
    return x + 2


def _add_two_with_kwargs(**kwargs):
    """Same as :func:`_add_two`, but accepting the arguments as keyword arguments."""
    return kwargs["x"] + 2


def _run_generated_script(function, parameters):
    """Generate the function step task script and execute it.

    :param function: The function to use as the pipeline step.
    :param parameters: The task parameters as they are read back from the task,
        i.e. after the pipeline resolved the parameter values and cast them to
        the declared type.
    :return: The value returned by the user function.
    """
    # The imports are done inside the function on purpose: the generated task
    # script copies the global imports of the module the function is defined
    # in, and those must not shadow the task class used by the script.
    import clearml
    from clearml.backend_interface.task.populate import CreateFromFunction
    from clearml.backend_interface.task.task import Task

    _TASK_PARAMETERS.clear()
    _TASK_PARAMETERS.update(parameters)

    # The project id is the only part of the task creation that requires a
    # ClearML server, it is not relevant for the generated script.
    with mock.patch.object(Task, "get_project_id", return_value="unittest-project-id"):
        task_definition = CreateFromFunction.create_task_from_function(
            a_function=function,
            function_kwargs={"x": "${pipeline.x}"},
            project_name="unittest",
            task_name="unittest",
            task_type="training",
            auto_connect_frameworks=False,
            auto_connect_arg_parser=False,
            packages=False,
            dry_run=True,
        )
    script = task_definition["script"]["diff"]

    original_task = clearml.Task
    clearml.Task = _FakeTask
    namespace = {"__name__": "__main__"}
    try:
        exec(compile(script, "<generated function step>", "exec"), namespace)  # noqa: S102
    finally:
        clearml.Task = original_task
    return namespace["results"]


def test_function_step_receives_typed_parameter_value():
    """The function must receive the pipeline parameter value, not its string placeholder."""
    # The parameter was declared as an int, so the task returns it as an int.
    assert _run_generated_script(_add_two, {"kwargs/x": 120}) == 122


def test_function_step_with_kwargs_receives_typed_parameter_value():
    """The same must hold for functions that accept ``**kwargs``."""
    assert _run_generated_script(_add_two_with_kwargs, {"kwargs/x": 120}) == 122
